// Regenerates packages/shared-types/src/api.ts from the FastAPI OpenAPI schema.
// Source of truth for request/response types is the backend (Pydantic); never edit api.ts by hand.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import openapiTS, { astToString } from "openapi-typescript";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const apiDir = join(root, "services", "api");
const python = [
  join(apiDir, ".venv", "Scripts", "python.exe"),
  join(apiDir, ".venv", "bin", "python"),
].find(existsSync);

if (!python) {
  console.error("services/api/.venv not found. Create it first (see README).");
  process.exit(1);
}

const schemaPath = join(apiDir, "openapi.json");
execFileSync(python, [join(apiDir, "scripts", "export_openapi.py"), schemaPath], { cwd: apiDir, stdio: "inherit" });

// Pass the parsed object instead of a path: the CLI's file resolver breaks on non-ASCII directory names.
const schema = JSON.parse(readFileSync(schemaPath, "utf8"));
const ast = await openapiTS(schema);
const header = "// Generated by `npm run gen:api` from services/api OpenAPI. Do not edit by hand.\n\n";
const out = join(root, "packages", "shared-types", "src", "api.ts");
writeFileSync(out, header + astToString(ast));
console.log(`wrote ${out}`);
