# 돌려받아야 어떤 제안이 어떤 글인지 서버가 맞춰 저장할 수 있다.


# ── 외부 교사 질문: 분야 추천 ─────────────────────────────────
# 학생이 어려운 분류를 직접 고르지 않아도, 연구 내용을 보고 AI가 분야
# 키워드를 추천한다(§16). 이 키워드로 교사 매칭을 한다.


# ── 외부 교사 질문: 답변을 연구에 반영 ───────────────────────────
# 교사 답변을 학생이 "연구에 반영하기" 눌렀을 때, 어느 단계에 어울리고
# 무엇을 반영하면 좋을지 정리한다. 이 결과를 논문에 자동으로 넣지 않는다
# (§19) — 학생이 승인해야 참고된다.


def fill(template: str, **values) -> str:
    """지시문의 {{이름}} 자리를 채운다.

    `.format()` 을 쓰지 않는 이유는 지시문 안의 JSON 예시 중괄호까지
    자리로 보고 터지기 때문이다. 아는 이름만 골라 바꾼다.
    """
    out = template
    for key, value in values.items():
        out = out.replace("{{" + key + "}}", str(value))
    return out
