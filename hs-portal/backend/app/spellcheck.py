# 실제로 검사에 쓸 규칙만 남긴다(skip 은 참고용으로 사전에만 둔다).
ACTIVE_RULES = [r for r in RULES if r[3] in ("sure", "maybe")]


def check(text: str) -> List[Dict]:
    """문장에서 고칠 만한 표현을 찾는다.

    같은 자리에서 여러 규칙이 겹치면 먼저 찾은 것만 남긴다.
    돌려주는 위치(start, end)는 원문 문자열 기준이라 화면에서 그대로 바꿀 수 있다.
    """
    body = text or ""
    found = []
    taken = []          # 이미 지적한 구간

    for wrong, right, reason, level in ACTIVE_RULES:
        for m in re.finditer(re.escape(wrong), body):
            start, end = m.start(), m.end()
            if any(not (end <= s or start >= e) for s, e in taken):
                continue        # 앞선 지적과 겹치면 건너뛴다
            taken.append((start, end))
            found.append({
                "start": start,
                "end": end,
                "found": wrong,
                "suggest": right,
                "reason": reason,
                "level": level,     # sure = 고치는 것이 맞음, maybe = 확인 권함
            })

    found.sort(key=lambda x: x["start"])
    return found


def check_many(texts: Dict[str, str]) -> Dict[str, List[Dict]]:
    """항목별로 한꺼번에 검사한다. {항목키: 본문} -> {항목키: [지적, ...]}"""
    return {key: check(value) for key, value in (texts or {}).items() if (value or "").strip()}


def rule_count() -> int:
    return len(ACTIVE_RULES)
