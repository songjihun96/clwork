def load_guide(db: Session) -> dict:
    """저장된 표가 있으면 그것을, 없으면 기본값을 준다.

    기본값을 돌려줄 때는 복사본을 준다 — 부르는 쪽이 고치다가 이 파일의
    기본값까지 바꿔 버리면, 서버를 다시 켤 때까지 모두에게 그 값이 보인다.
    """
    row = db.get(Setting, SETTING_KEY)
    if row and (row.value or "").strip():
        try:
            saved = json.loads(row.value)
            if isinstance(saved, dict) and saved:
                return saved
        except ValueError:
            pass
    return copy.deepcopy(DEFAULT_GUIDE)


def save_guide(db: Session, guide: dict) -> None:
    value = json.dumps(guide, ensure_ascii=False)
    row = db.get(Setting, SETTING_KEY)
    if row is None:
        db.add(Setting(key=SETTING_KEY, value=value))
    else:
        row.value = value
    db.commit()


def jobs_of(db: Session, group: str) -> list:
    return (load_guide(db).get(group) or {}).get("jobs") or []
