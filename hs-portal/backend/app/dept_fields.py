# 학과로 볼 수 없는 이름(일반계 과정 등)은 분류에서 뺀다.
IGNORE = ("보통과", "일반과", "인문과", "자연과", "공통과정", "일반계")

FIELD_LABEL: Dict[str, str] = {key: label for key, label, _ in FIELDS}


def classify_one(name: str) -> List[str]:
    """학과명 하나를 계열 키 목록으로 바꾼다."""
    text = (name or "").replace(" ", "")
    if not text or any(ig in text for ig in IGNORE):
        return []
    hits = []
    for key, _label, words in FIELDS:
        if any(w in text for w in words):
            hits.append(key)
    return hits


def classify(departments_text: str) -> List[str]:
    """줄바꿈으로 구분된 학과 목록에서 계열 키를 뽑는다(중복 제거, 정의 순서 유지)."""
    found = set()
    for line in (departments_text or "").splitlines():
        found.update(classify_one(line))
    return [key for key, _l, _w in FIELDS if key in found]


def to_storage(departments_text: str) -> str:
    """DB에 저장할 형태(쉼표로 감싼 문자열). LIKE 검색이 쉽도록 앞뒤에 쉼표를 둔다."""
    keys = classify(departments_text)
    return ("," + ",".join(keys) + ",") if keys else ""


