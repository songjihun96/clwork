def _clean_name(name: str) -> str:
    """학교명 비교용 정규화. 공백만 없애고 나머지는 그대로 둔다 —
    "OO고등학교"를 "OO고"로 줄이는 식의 축약은 서로 다른 학교를 잘못
    같다고 판단할 위험이 있어 하지 않는다."""
    return (name or "").strip().replace(" ", "")


def fetch_one_district(api_key: str, year: int, sido_code: str, sgg_code: str) -> List[Dict]:
    params = {
        "apiKey": api_key,
        "apiType": API_TYPE_DORMITORY,
        "pbanYr": str(year),
        "schulKndCode": SCHUL_KND_HS,
        "sidoCode": sido_code,
        "sggCode": sgg_code,
    }
    res = requests.get(SCHOOLINFO_ENDPOINT, params=params, timeout=30)
    res.raise_for_status()
    try:
        data = res.json()
    except ValueError:
        print(f"  [{sido_code}/{sgg_code}] 응답이 JSON이 아닙니다(앞부분): {res.text[:200]}")
        return []

    code = data.get("resultCode", "")
    if code and code != "success":
        print(f"  [{sido_code}/{sgg_code}] 학교알리미 응답: {code} {data.get('resultMsg', '')}")
        return []
    return data.get("list", [])


def fetch_dormitory_rows(api_key: str, year: int) -> List[Dict]:
    """전국 고등학교의 교사(校舍) 현황을 시/군/구 단위로 나눠(256곳) 받아
    합친다. 한 지역 요청이 실패해도(네트워크 오류 등) 나머지는 계속 받는다.
    지역이 많아 시간이 좀 걸린다 — 20곳마다 진행 상황을 알린다."""
    rows: List[Dict] = []
    current_sido = None
    for i, (sido_code, sgg_code) in enumerate(SGG_CODES, start=1):
        if sido_code != current_sido:
            current_sido = sido_code
            print(f"  [{SIDO_LABELS.get(sido_code, sido_code)}] 받는 중…")
        try:
            page = fetch_one_district(api_key, year, sido_code, sgg_code)
        except requests.RequestException as exc:
            print(f"  [{sido_code}/{sgg_code}] 요청 실패, 건너뜀: {exc}")
            continue
        rows.extend(page)
        if i % 20 == 0:
            print(f"  ({i}/{len(SGG_CODES)}곳 완료, 지금까지 {len(rows)}건)")
        time.sleep(0.1)
    return rows


def parse_room_count(raw: object) -> Optional[int]:
    """COL_13 값을 정수로. 빈 값·비숫자는 '모름'으로 처리한다(0으로 단정하지 않는다)."""
    if raw is None:
        return None
    s = str(raw).strip().replace(",", "")
    if not s:
        return None
    try:
        return int(float(s))
    except ValueError:
        return None


def iter_matches(rows: List[Dict]) -> Iterator[Dict]:
    """정보공시 제외 학교·폐교는 건너뛰고, 이름 정규화 키를 붙여 내보낸다."""
    for row in rows:
        if (row.get("PBAN_EXCP_YN") or "").upper() == "Y":
            continue  # 이 항목만 공시 제외 신청한 학교. COL_13이 비어 있어도 '없음'이 아니다.
        name = row.get("SCHUL_NM") or ""
        if not name:
            continue
        rooms = parse_room_count(row.get("COL_13"))
        if rooms is None:
            continue
        yield {"name": name, "key": _clean_name(name), "rooms": rooms}


def main() -> int:
    parser = argparse.ArgumentParser(
        description="학교알리미 교사(校舍) 현황에서 기숙사실수를 받아 School.dormitory를 채운다.")
    parser.add_argument("--year", type=int, default=None,
                        help="공시연도(yyyy). 기본은 올해(최근 3년만 제공됨).")
    parser.add_argument("--force", action="store_true",
                        help="이미 dormitory 값이 있는 학교도 새로 덮어쓴다.")
    parser.add_argument("--dry-run", action="store_true",
                        help="DB에 저장하지 않고 몇 곳이 True/False로 바뀔지만 보여준다.")
    args = parser.parse_args()

    api_key = os.getenv("SCHOOLINFO_API_KEY", "").strip()
    if not api_key:
        print("SCHOOLINFO_API_KEY가 없습니다. 아래에서 발급받아 환경변수로 넣어주세요.")
        print("  https://www.schoolinfo.go.kr → OpenAPI → 로그인(소셜미디어) → 나의 정보 조회")
        return 1

    from datetime import date
    year = args.year or date.today().year

    print(f"{year}년도 교사(校舍) 현황을 받는 중…")
    try:
        rows = fetch_dormitory_rows(api_key, year)
    except requests.RequestException as exc:
        print(f"학교알리미 요청이 실패했습니다: {exc}")
        return 1

    if not rows:
        print("받은 자료가 없습니다. 연도를 바꿔 다시 시도해보세요(최근 3년만 제공됩니다).")
        return 1
    print(f"{len(rows)}개 학교 자료를 받았습니다.")

    by_name: Dict[str, Dict] = {}
    for m in iter_matches(rows):
        # 같은 이름 학교가 둘 이상이면(드묾) 기숙사실수가 더 큰 쪽을 우선한다 —
        # 어느 한 쪽이라도 있다고 나오면 그 이름으로는 "있음"에 가깝다고 본다.
        prev = by_name.get(m["key"])
        if prev is None or m["rooms"] > prev["rooms"]:
            by_name[m["key"]] = m

    db: Session = SessionLocal()
    matched = updated = skipped_existing = 0
    unmatched: List[str] = []
    try:
        schools = db.query(School).all()
        for school in schools:
            hit = by_name.get(_clean_name(school.name))
            if not hit:
                unmatched.append(school.name)
                continue
            matched += 1
            if school.dormitory is not None and not args.force:
                skipped_existing += 1
                continue
            new_value = hit["rooms"] > 0
            if school.dormitory != new_value:
                print(f"  {school.name} ({school.region}): "
                      f"dormitory {school.dormitory} → {new_value} (기숙사실수 {hit['rooms']})")
                school.dormitory = new_value
                updated += 1
        if not args.dry_run:
            db.commit()
        else:
            db.rollback()
    finally:
        db.close()

    print(
        f"\n완료 — DB 학교 {len(unmatched) + matched}곳 중 이름으로 이어붙인 곳 {matched}곳, "
        f"실제로 바뀐 곳 {updated}곳"
        + (" (dry-run, 저장 안 함)" if args.dry_run else "")
    )
    if skipped_existing:
        print(f"이미 값이 있어 건드리지 않은 곳 {skipped_existing}곳 (--force 로 덮어쓸 수 있습니다)")
    if unmatched:
        print(f"학교알리미 자료에서 이름이 안 맞아 못 찾은 곳 {len(unmatched)}곳"
              f"(개교/폐교 시점 차이나 표기 차이일 수 있습니다):")
        for name in unmatched[:30]:
            print(f"  - {name}")
        if len(unmatched) > 30:
            print(f"  ... 외 {len(unmatched) - 30}곳")

    return 0


if __name__ == "__main__":
    sys.exit(main())
