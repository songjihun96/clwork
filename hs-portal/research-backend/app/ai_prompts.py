def fill(template: str, **values) -> str:
    """지시문의 {{이름}} 자리를 채운다.

    `.format()` 을 쓰지 않는 이유는 지시문 안의 JSON 예시 중괄호까지
    자리로 보고 터지기 때문이다. 아는 이름만 골라 바꾼다.
    """
    out = template
    for key, value in values.items():
        out = out.replace("{{" + key + "}}", str(value))
    return out
